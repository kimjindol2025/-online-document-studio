// Static compatibility build: definitions/*.json -> browser catalog + SEO entry pages.
// No network, no document user data, no changes to existing quotation application.
import {readFileSync,readdirSync,writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import {dirname,join} from "node:path";
import {validateDefinition,escapeHtml} from "./prototype/engine.mjs";
import {buildBusinessCore} from './build-business-core.mjs';

buildBusinessCore();

const root=dirname(fileURLToPath(import.meta.url));
const definitionsDir=join(root,"definitions");
const prototypeDir=join(root,"prototype");
const docs=readdirSync(definitionsDir).filter(f=>f.endsWith(".json")).sort()
  .map(f=>JSON.parse(readFileSync(join(definitionsDir,f),"utf8")));
const slugs=new Set();
for(const doc of docs){
  const errors=validateDefinition(doc);
  if(errors.length)throw Error(doc.id+": "+errors.join(", "));
  if(slugs.has(doc.slug))throw Error("중복 슬러그: "+doc.slug);
  slugs.add(doc.slug);
}
const publicDocs=docs.filter(d=>d.status==="public");
writeFileSync(join(prototypeDir,"generated-catalog.mjs"),
  "// Generated by build-catalog.mjs. Edits will be overwritten.\n"+
  "export const definitions = "+JSON.stringify(publicDocs,null,2)+";\n","utf8");

for(const doc of publicDocs) {
  const title=escapeHtml(doc.seo?.title||doc.title+" | 무료 문서 작성기");
  const desc=escapeHtml(doc.seo?.description||doc.summary);
  const name=escapeHtml(doc.title),notice=escapeHtml(doc.notice);
  const html="<!doctype html>\n"+
    "<html lang='ko'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>"+
    "<meta name='description' content='"+desc+"'><meta name='robots' content='noindex'><title>"+title+"</title>"+
    "<style>body{margin:0;background:#f4f7fa;font:16px/1.7 system-ui,sans-serif;color:#142a42}main{max-width:680px;margin:9vh auto;background:#fff;padding:36px;border:1px solid #dce4ee;border-radius:16px}small{color:#476781}h1{margin:8px 0 16px;line-height:1.35}p{color:#536579}.cta{display:inline-block;background:#165c97;color:#fff;padding:11px 19px;border-radius:10px;text-decoration:none;font-weight:bold}.muted{margin-top:22px;font-size:13px;color:#6a7d90}@media(max-width:720px){main{margin:16px;padding:22px}}</style>"+
    "</head><body><main><small>"+escapeHtml(doc.category)+" · 무료 작성·인쇄</small><h1>"+name+"</h1>"+
    "<p>"+escapeHtml(doc.summary)+"</p><p>"+notice+"</p>"+
    "<a class='cta' href='./index.html?doc="+encodeURIComponent(doc.slug)+"'>바로 작성 · 빈 양식 인쇄</a>"+
    "<p class='muted'>회원가입 없이 이용할 수 있으며 입력 내용은 기본적으로 이 기기 안에서만 처리합니다. 실제 PDF 저장은 브라우저 인쇄 화면에서 선택하세요.</p>"+
    "</main></body></html>";
  writeFileSync(join(prototypeDir,"doc-"+doc.slug+".html"),html,"utf8");
}
process.stdout.write("PASS: "+docs.length+" definitions ("+publicDocs.length+" public + "+(docs.length-publicDocs.length)+" internal), generated "+
  publicDocs.length+" SEO pages\n");
